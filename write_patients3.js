A("              className=\"text-on-surface-variant hover:text-red-500 transition-colors flex-shrink-0\"");
A("            >");
A("              <span className=\"material-symbols-outlined text-lg\">close</span>");
A("            </button>");
A("          )}");
A("        </div>");
A("        <select");
A("          value={filterStatut}");
A("          onChange={(e) => setFilterStatut(e.target.value)}");
A("          className=\"px-4 py-2 rounded-lg border border-outline-variant bg-surface text-sm text-on-surface focus:outline-none\"");
A("        >");
A("          <option value=\"tous\">{t('pat_tousLesStatuts')}</option>");
A("          <option value=\"actif\">{t('pat_actif')}</option>");
A("          <option value=\"inactif\">{t('pat_inactif')}</option>");
A("          <option value=\"en_attente\">{t('pat_enAttente')}</option>");
A("          <option value=\"archive\">{t('pat_archive')}</option>");
A("        </select>");
A("        {(search || filterStatut !== 'tous') && (");
A("          <button");
A("            onClick={() => { setSearch(''); setFilterStatut('tous') }}");
A("            className=\"px-4 py-2 rounded-lg border border-outline-variant bg-surface text-sm text-red-500 font-semibold hover:bg-red-50 transition-colors flex items-center gap-2\"");
A("          >");
A("            <span className=\"material-symbols-outlined text-lg\">filter_alt_off</span>");
A("            {t('pat_toutAfficher')}");
A("          </button>");
A("        )}");
A("      </div>");
A("");
A("      {loading ? (");
A("        <div className=\"flex flex-col items-center justify-center py-24 text-on-surface-variant\">");
A("          <div className=\"w-10 h-10 border-4 border-primary border-t-transparent rounded-full animate-spin mb-4\"></div>");
A("          <p className=\"text-sm\">{t('pat_chargement')}</p>");
A("        </div>");
A("      ) : (");
A("        <div className=\"bg-surface rounded-xl border border-outline-variant shadow-sm overflow-hidden\">");
A("          <div className=\"overflow-x-auto\">");
