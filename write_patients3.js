A("                  <th className=\"table-header\">{t('pat_colStatut')}</th>");
A("                  <th className=\"table-header\">{t('pat_colDerniereVisite')}</th>");
A("                  <th className=\"table-header text-center\">{t('pat_colArchive')}</th>");
A("                  <th className=\"table-header w-10\"></th>");
A("                </tr>");
A("              </thead>");
A("              <tbody>");
