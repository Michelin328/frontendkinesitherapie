A("                  <tr key={p.id} className=\"hover:bg-surface-container-low/50 transition-colors\">");
A("                    <td className=\"table-cell\">");
A("                      <span className=\"text-xs font-mono text-primary font-semibold\">{p.numeroDossier || '-'}</span>");
A("                    </td>");
A("                    <td className=\"table-cell\">");
A("                      <Link href={'/patients/' + p.id} className=\"hover:underline\">");
