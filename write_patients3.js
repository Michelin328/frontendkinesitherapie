A("            placeholder={t('pat_rechercherPlaceholder')}");
A("            value={search}");
A("            onChange={(e) => setSearch(e.target.value)}");
A("            className=\"bg-transparent border-none focus:outline-none text-sm w-full text-on-surface placeholder:text-on-surface-variant\"");
A("          />");
