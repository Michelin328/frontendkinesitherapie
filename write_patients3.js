A("        </div>");
A("        <Link href=\"/patients/nouveau\" className=\"btn-primary\">");
A("          <span className=\"material-symbols-outlined text-lg\">person_add</span>");
A("          {t('pat_nouveauPatient')}");
A("        </Link>");
A("      </div>");
A("");
